import { auth } from '@/lib/auth'
import { db } from '@/lib/db'
import { apiError } from '@/lib/utils'

export async function GET(
  _req: Request,
  { params }: { params: Promise<{ uuid: string }> },
) {
  const session = await auth()
  if (!session?.user) return apiError('Unauthorized', 401)

  const { uuid } = await params

  const benchmark = await db.benchmark.findUnique({
    where: { uuid },
    include: {
      scores: true,
      results: { orderBy: [{ category: 'asc' }, { metricName: 'asc' }] },
      locations: { orderBy: { testLocation: 'asc' } },
      provider: { select: { name: true } },
      country: { select: { name: true, flagEmoji: true } },
    },
  })

  if (!benchmark) return apiError('Benchmark not found', 404)
  if (benchmark.userId !== session.user.id) return apiError('Forbidden', 403)

  const score = benchmark.scores[0]
  const lines: string[] = []

  lines.push(`# Benchmark Report — ${benchmark.hostname || benchmark.ipv4 || uuid}`)
  lines.push('')
  lines.push(`**Submitted:** ${benchmark.createdAt.toISOString()}`)
  lines.push(`**UUID:** \`${uuid}\``)
  if (benchmark.provider) lines.push(`**Provider:** ${benchmark.provider.name}`)
  if (benchmark.country) lines.push(`**Location:** ${benchmark.country.flagEmoji ?? ''} ${benchmark.country.name}`)
  lines.push('')

  // System info
  lines.push('## System Information')
  lines.push('')
  lines.push('| Field | Value |')
  lines.push('|-------|-------|')
  const sysFields: [string, string | number | null | undefined][] = [
    ['OS', `${benchmark.osName ?? ''} ${benchmark.osVersion ?? ''}`.trim() || null],
    ['Kernel', benchmark.kernel],
    ['Architecture', benchmark.architecture],
    ['Virtualization', benchmark.virtualization],
    ['CPU', benchmark.cpuModel],
    ['CPU Cores', benchmark.cpuCores],
    ['RAM', benchmark.ramTotalMb ? `${benchmark.ramTotalMb} MB` : null],
    ['Disk', benchmark.diskTotalGb ? `${benchmark.diskTotalGb} GB` : null],
    ['IPv4', benchmark.ipv4],
    ['IPv6', benchmark.ipv6],
    ['Uptime', benchmark.uptimeSeconds ? `${Math.round(Number(benchmark.uptimeSeconds) / 3600)}h` : null],
    ['Load Average', benchmark.loadAverage],
  ]
  for (const [k, v] of sysFields) {
    if (v) lines.push(`| ${k} | ${v} |`)
  }
  lines.push('')

  // Scores
  if (score) {
    lines.push('## Performance Scores')
    lines.push('')
    lines.push('| Category | Score |')
    lines.push('|----------|-------|')
    lines.push(`| **Total** | **${score.totalScore?.toFixed(1) ?? '—'}** |`)
    lines.push(`| CPU | ${score.cpuScore?.toFixed(1) ?? '—'} |`)
    lines.push(`| Disk | ${score.diskScore?.toFixed(1) ?? '—'} |`)
    lines.push(`| Memory | ${score.memoryScore?.toFixed(1) ?? '—'} |`)
    lines.push(`| Network | ${score.networkScore?.toFixed(1) ?? '—'} |`)
    lines.push(`| Security | ${score.securityScore?.toFixed(1) ?? '—'} |`)
    if (score.confidenceLevel) lines.push(`| Confidence | ${score.confidenceLevel} |`)
    if (score.stabilityBonus != null) lines.push(`| Stability Bonus | ${score.stabilityBonus > 0 ? '+' : ''}${score.stabilityBonus?.toFixed(1)} |`)
    if (score.regionPercentile != null) lines.push(`| Region Percentile | ${score.regionPercentile}th |`)
    lines.push('')
  }

  // Benchmark results by category
  const byCategory: Record<string, typeof benchmark.results> = {}
  for (const r of benchmark.results) {
    if (!byCategory[r.category]) byCategory[r.category] = []
    byCategory[r.category].push(r)
  }

  for (const [cat, results] of Object.entries(byCategory)) {
    lines.push(`## ${cat.charAt(0).toUpperCase() + cat.slice(1)} Results`)
    lines.push('')
    lines.push('| Metric | Value | Unit |')
    lines.push('|--------|-------|------|')
    for (const r of results) {
      lines.push(`| ${r.metricName} | ${r.metricValue.toLocaleString()} | ${r.unit ?? ''} |`)
    }
    lines.push('')
  }

  // Network tests
  if (benchmark.locations.length > 0) {
    lines.push('## Network Speed Tests')
    lines.push('')
    lines.push('| Location | Download (Mbps) | Upload (Mbps) | Ping (ms) | Jitter (ms) |')
    lines.push('|----------|----------------|---------------|-----------|-------------|')
    for (const l of benchmark.locations) {
      lines.push(`| ${l.testLocation} | ${l.downloadMbps?.toFixed(1) ?? '—'} | ${l.uploadMbps?.toFixed(1) ?? '—'} | ${l.pingMs?.toFixed(1) ?? '—'} | ${l.jitterMs?.toFixed(1) ?? '—'} |`)
    }
    lines.push('')
  }

  lines.push('---')
  lines.push(`*Generated by [HiTech Benchmark](${process.env.NEXT_PUBLIC_SITE_URL || 'https://hitechbenchmark.com'}) on ${new Date().toISOString()}*`)

  const body = lines.join('\n')
  const filename = `benchmark-${uuid.slice(0, 8)}.md`

  return new Response(body, {
    headers: {
      'Content-Type': 'text/markdown; charset=utf-8',
      'Content-Disposition': `attachment; filename="${filename}"`,
      'Cache-Control': 'no-store',
    },
  })
}
